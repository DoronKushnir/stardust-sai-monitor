scan = d["snr_scan"]; resp = d["response_knowledge"]; mc = d["monte_carlo"]
rho = d["rho_slant_to_shell_20km"]


def f3(x):
    return f"{3*x:.3f}"


def sci(x):
    m, e = f"{x:.2e}".split("e")
    return m + "\\times10^{" + str(int(e)) + "}"


rows_mc = []
for m, r in mc["baseline"].items():
    rows_mc.append(f"baseline & {float(m):.2f} & {r['bias_median']:+.4f} & {r['sd']:.4f} & {r['posterior_sigma_median']:.4f} & "
                   f"{100*r['coverage_1sig']:.0f} / {100*r['coverage_2sig']:.0f} & {100*r['p_detect_3sig']:.0f} / {100*r['p_detect_4p54sig']:.0f} \\\\")
labels = dict(no_line_errors="no line errors", no_response_pert="response known", response_sigma_0p01="registration error $0.01~\\mu$m",
              tropical_o3_0p4="tropical O$_3$ ($\\times0.4$)", sigma_eta_0p05="per-line scatter $5\\,\\%$",
              sigma_eta_0p01="per-line scatter $1\\,\\%$", mir_alone="window alone (no triplet)")
for k, lab in labels.items():
    if k not in mc:
        continue
    r0 = mc[k]["0.0"]; r1 = mc[k]["0.1"]
    rows_mc.append(f"{lab} & 0 / 0.10 & {r0['bias_median']:+.4f} / {r1['bias_median']:+.4f} & {r0['sd']:.4f} / {r1['sd']:.4f} & "
                   f"{r0['posterior_sigma_median']:.4f} / {r1['posterior_sigma_median']:.4f} & {100*r1['coverage_1sig']:.0f} / {100*r1['coverage_2sig']:.0f} & "
                   f"{100*r0['p_detect_3sig']:.0f} / {100*r1['p_detect_3sig']:.0f} \\\\")

