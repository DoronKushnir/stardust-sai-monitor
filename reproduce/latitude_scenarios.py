# Ported from the working repository's scripts/paper1_latitude_scenarios_round67.py (paper 1 round 67).
"""
paper1_latitude_scenarios_round67.py -- referee round 4, item 8: one table
separating (i) the spatial sensitivity under the reference-atmosphere floor,
(ii) the measured altitude-dependent ACE floor and (iii) the measured-ozone
rescaled scenario, with the fixed-20-km and best-height coverages in
separate columns, read from the archived 2-D maps of
detectability_2d_calibrated.py (map_pm41.npz, map_pm41_o3lat.npz; the
+-41 deg, 51 hPa sustained-injection field).  Resolves the 65S-67N vs
69S-73N statements of Sect. 6 (the first is the fixed-20-km coverage under
the reference floor, the second the best-height coverage under the measured
floor; both are regenerated here).

Run from the repo root:  python reproduce/latitude_scenarios.py
Outputs: outputs/latitude_scenarios.json, tables/latitude_scenarios.tex
"""
from __future__ import annotations
import json
from pathlib import Path
import numpy as np
_ROOT = Path(__file__).resolve().parent.parent
D = _ROOT / "outputs" / "detectability_2d_calibrated"
Z20 = 20.47   # the model level nearest 20.5 km (Sect. 6)

def cov(lat, m):
    ok = m <= 0.1
    if not ok.any(): return None
    return float(lat[ok].min()), float(lat[ok].max()), float(ok.mean())

rows = []
for scen, fn, key, support in (
    ("reference-atmosphere floor", "map_pm41.npz", "mmin_band_quiet_oe", "US-standard ozone at every latitude; floors re-derived per tangent altitude"),
    ("measured altitude-dependent floor", "map_pm41.npz", "mmin_band_quiet_atlas", "ACE 20--25$^\\circ$N Jun--Aug, 16--19 / 19--22 / 22--25 km"),
    ("measured-ozone rescaled floor", "map_pm41_o3lat.npz", "mmin_band_quiet_oe", "ACE O$_3$ at 20--25$^\\circ$N, 35--55$^\\circ$N, 60--90$^\\circ$S; symmetric, year-round"),
    ("measured-ozone + measured floor", "map_pm41_o3lat.npz", "mmin_band_quiet_atlas", "both of the above")):
    z = np.load(D / fn); lat = z["lat_deg"]; zl = z["z_lev_km"]; m = z[key]   # (lat, z) or (z, lat)
    if m.shape[0] != len(lat): m = m.T
    k = int(np.argmin(np.abs(zl - Z20)))
    m20 = m[:, k]; best = np.nanmin(m, axis=1)
    c20 = cov(lat, m20); cb = cov(lat, best)
    r = dict(scenario=scen, support=support, z20_level=float(zl[k]),
             fixed20_min=float(np.nanmin(m20)), fixed20_max=float(np.nanmax(m20)), fixed20_cov=c20,
             best_min=float(np.nanmin(best)), best_worst=float(np.nanmax(best)), best_cov=cb)
    rows.append(r); print(json.dumps(r))
out = _ROOT / "outputs" / "latitude_scenarios.json"; out.write_text(json.dumps(rows, indent=2))
def rng(c): return "all latitudes" if c and c[2] >= 0.999 else (f"{-c[0]:.0f}$^\\circ$S--{c[1]:.0f}$^\\circ$N" if c else "none")
tex = ["% generated by reproduce/latitude_scenarios.py from the archived 2-D maps (round 67, referee item 8)",
       "\\begin{table*}[t]", "\\centering",
       "\\caption{Single-sounding $3\\sigma$ sensitivity to $0.1$~Tg of silica in the $\\pm41^\\circ$ sustained-injection field (band configuration) under the three error scenarios of Sect.~\\ref{sec:2d}. ``Fixed $20$~km'' is the $20.5$-km tangent bin alone; ``best height'' takes the most sensitive bin at each latitude. Coverage is the latitude range over which the threshold is below $0.1$~Tg; ``worst'' is the largest best-height threshold on the map. The latitude and season of the measurements behind each scenario are given in the second column; outside them the scenario is an assumption, not a measurement. Whether the orbit observes a latitude is a separate question (Sect.~\\ref{sec:2d}).}",
       "\\label{tab:latitude_scenarios}", "\\small", "\\begin{tabular}{llcccc}", "\\toprule",
       "Scenario & Measurement support & Fixed $20$~km: range (Tg) & Fixed $20$~km: $<0.1$~Tg & Best height: worst (Tg) & Best height: $<0.1$~Tg \\\\", "\\midrule"]
for r in rows:
    tex.append(f"{r['scenario']} & {r['support']} & {r['fixed20_min']:.3f}--{r['fixed20_max']:.2f} & {rng(r['fixed20_cov'])} & {r['best_worst']:.3f} & {rng(r['best_cov'])} \\\\")
tex += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
(_ROOT / "tables/latitude_scenarios.tex").write_text("\n".join(tex) + "\n")
print("wrote", out, "and tables/latitude_scenarios.tex")
